// SITE777 browser collector V3
// Start this on the hall's HallSelectLink.do page while logged in.
// It uses the site's own buttons/forms instead of guessing private routes.
(async()=>{
 const wait=ms=>new Promise(r=>setTimeout(r,ms));
 const parse=s=>new DOMParser().parseFromString(s,'text/html');
 const norm=s=>(s||'').replace(/\s+/g,' ').trim();
 const hallUrl=new URL(location.href);
 const hallcode=hallUrl.searchParams.get('hallcode')||'';
 const models=[],machines=[],history=[];

 // 1) Read the actual hall/model-list HTML.
 const hallHtml=await fetch(hallUrl,{credentials:'include',cache:'no-store'}).then(r=>r.text());
 const hd=parse(hallHtml);

 // SITE777 model blocks contain a machine label/count plus select/list submit buttons.
 // Keep only the [4] pachinko section; stop when the next rate section begins.
 let in4=false;
 const blocks=[];
 for(const el of hd.querySelectorAll('td,li,div')){
   const t=norm(el.textContent);
   if(/^【\s*4\s*】パチ/.test(t)){in4=true;continue}
   if(in4&&/^【\s*(?:1|20|5)\s*】/.test(t)){in4=false;continue}
   if(!in4)continue;
   const btn=[...el.querySelectorAll('input[type="button"],input[type="submit"]')];
   if(!btn.some(x=>/^(select|list)$/i.test(x.name||'')))continue;
   const mc=t.match(/(.+?)\s*\((\d+)\)/);
   if(mc)blocks.push({el,name:norm(mc[1]),count:+mc[2]});
 }
 const uniqBlocks=[...new Map(blocks.map(x=>[x.name,x])).values()];
 console.log('4円機種',uniqBlocks.length);

 // Capture the site's real navigation generated by a model button.
 const captureNavigation=async(block)=>{
   const btn=[...block.el.querySelectorAll('input[type="button"],input[type="submit"]')]
     .find(x=>/^(select|list)$/i.test(x.name||''));
   if(!btn)return null;

   // Prefer an explicit form action/GET/POST encoded in the HTML.
   const form=btn.form||block.el.closest('form');
   if(form){
     const p=new URLSearchParams();
     for(const e of [...form.elements]){
       if(!e.name||e.disabled)continue;
       if((e.type==='checkbox'||e.type==='radio')&&!e.checked)continue;
       p.append(e.name,e.value||'');
     }
     if(btn.name)p.set(btn.name,btn.value||'');
     const action=new URL(form.getAttribute('action')||location.href,location.href);
     if((form.method||'get').toLowerCase()==='post'){
       const r=await fetch(action,{method:'POST',credentials:'include',cache:'no-store',
         headers:{'Content-Type':'application/x-www-form-urlencoded'},body:p});
       return {url:r.url,html:await r.text()};
     }
     action.search=p.toString();
     const r=await fetch(action,{credentials:'include',cache:'no-store'});
     return {url:r.url,html:await r.text()};
   }
   return null;
 };

 // 2) Open every model with the exact form/button data supplied by SITE777.
 for(let i=0;i<uniqBlocks.length;i++){
   const b=uniqBlocks[i];
   try{
     const page=await captureNavigation(b);
     if(!page)continue;
     const d=parse(page.html);
     const links=[...d.querySelectorAll('[onclick*="tableNumClick"]')];
     const found=[];
     for(const a of links){
       const oc=a.getAttribute('onclick')||'';
       const token=oc.match(/tableNumClick\(['"]([^'"]+)['"]\)/i)?.[1];
       const no=norm(a.textContent).match(/台番[:：]?\s*(\d+)/)?.[1];
       if(!token||!no)continue;
       const box=a.closest('dd,li,td,div')||a.parentElement;
       const img=box?.querySelector('img[src*="RequestPcDedamaTransitionKahenRangeChart"]');
       found.push({model:b.name,machineNo:no,tableToken:token,
         chartUrl:img?new URL(img.getAttribute('src'),page.url).href:'',pageUrl:page.url});
     }
     const u=[...new Map(found.map(x=>[x.machineNo,x])).values()];
     machines.push(...u);
     models.push({model:b.name,expectedMachines:b.count,machines:u.length,pageUrl:page.url});
     console.log('['+(i+1)+'/'+uniqBlocks.length+']',b.name,u.length+'/'+b.count+'台');
   }catch(e){console.warn('機種失敗',b.name,e)}
   await wait(250);
 }

 // 3) For each discovered machine, use the already-proven GraphList.do day=0..7 route.
 const baseForm=document.HallDedamaActionForm||document.querySelector('form[action*="TableSelect.do"]');
 const uritanka=(baseForm?.elements?.uritanka?.value)||'400';
 for(let i=0;i<machines.length;i++){
   const x=machines[i];
   let modelcode='';
   try{modelcode=new URL(x.pageUrl).searchParams.get('modelcode')||new URL(x.pageUrl).searchParams.get('mdc')||''}catch{}
   for(let day=0;day<8;day++){
     try{
       const u=new URL('/pc/GraphList.do',location.origin);
       if(hallcode)u.searchParams.set('hallcode',hallcode);
       u.searchParams.set('tablenum',x.tableToken);
       u.searchParams.set('tablelistflag','1');
       u.searchParams.set('day',String(day));
       u.searchParams.set('currentpageno','1');
       u.searchParams.set('uritanka',uritanka);
       if(modelcode)u.searchParams.set('modelcode',modelcode);
       const r=await fetch(u,{credentials:'include',cache:'no-store'});
       const text=await r.text();
       history.push({model:x.model,machineNo:x.machineNo,tableToken:x.tableToken,
         modelcode,day,url:r.url,pageText:norm(parse(text).body?.innerText||text)});
     }catch(e){console.warn('履歴失敗',x.machineNo,day,e)}
     await wait(120);
   }
   console.log('履歴',i+1+'/'+machines.length,x.machineNo);
 }

 const data={source:'site777-browser-v3',hallcode,capturedAt:new Date().toISOString(),
   models,machines:[...new Map(machines.map(x=>[x.model+'|'+x.machineNo,x])).values()],history};
 const missing=models.filter(x=>x.machines!==x.expectedMachines);
 console.log('★★★★★ 完了 ★★★★★');
 console.log('機種',models.length,'台数',data.machines.length,'履歴',history.length,'不足機種',missing.length);
 if(missing.length)console.table(missing);
 const blob=new Blob([JSON.stringify(data,null,2)],{type:'application/json'});
 const a=document.createElement('a');a.href=URL.createObjectURL(blob);
 a.download='site777-4yen-all-'+new Date().toISOString().replace(/[:.]/g,'-')+'.json';a.click();
})();
